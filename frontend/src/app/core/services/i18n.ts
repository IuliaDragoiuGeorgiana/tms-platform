const TRANSLATIONS: Record<Language, TranslationDictionary> = {
  [Language.EN]: EN,
  [Language.RO]: RO,
  [Language.HU]: HU,
};

@Injectable({
  providedIn: 'root',
})
export class I18nService {
  readonly languages = [
    { code: Language.EN, icon: 'EN', label: 'English' },
    { code: Language.RO, icon: 'RO', label: 'Română' },
    { code: Language.HU, icon: 'HU', label: 'Magyar' },
  ];

  private readonly languageSubject = new BehaviorSubject<Language>(this.getStoredLanguage());
  readonly language$ = this.languageSubject.asObservable();

  get currentLanguage(): Language {
    return this.languageSubject.value;
  }

  setLanguage(language: Language): void {
    localStorage.setItem('language', language);
    this.languageSubject.next(language);
  }

  translate(key: string): string {
    return TRANSLATIONS[this.currentLanguage][key] ?? TRANSLATIONS[Language.EN][key] ?? key;
  }

  private getStoredLanguage(): Language {
    const storedLanguage = localStorage.getItem('language');
    return Object.values(Language).includes(storedLanguage as Language)
      ? (storedLanguage as Language)
      : Language.EN;
  }
}
